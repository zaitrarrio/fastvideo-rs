//! The `gold` tier: each gold variant's canonical cell (plan D4,
//! docs/adr/0023-lab-report-and-ci-bridge.md §3).
//!
//! `fv-lab run gold --all` runs one arm per gold file: the served variant
//! through the serve engine (`fv-gpucheck engine --model <variant>`, which
//! loads the variant from the family files with its own recipe and technique
//! profile, as fv-serve does) at the canvas and length of the file's
//! `[workload]`. The cells are data like every other cell
//! (`lab/cells/gold-<variant>.toml`, the `gold` tier of `lab/tiers.toml`),
//! but they are generated from `lab/gold/*.toml` and `families/*.toml` by
//! [`gold_cells`] (`fv-lab gold cells --write`), and a test holds the
//! committed files equal to it, so a gold file and its cell cannot drift.
//!
//! What the cell does not copy from the gold file, and why:
//! - the prompt set: the engine runs one request, so the cell runs
//!   [`GOLD_PROMPT`] (`runpod-matrix.sh`'s default prompt) once;
//! - `workload.env`: those settings reproduce an older measurement, and the
//!   gold run measures the served default;
//! - `steps`: the variant's recipe fixes them (the arm's `steps` is
//!   descriptive, as in every cell).

use fastvideo_manifest::{FamilySet, VariantManifest};

use crate::gold::Gold;
use crate::plan::{Arm, ArmBin, CellFile, Workload, CELL_SCHEMA};

/// The tier whose cells are generated from the gold files. Not a
/// `runpod-matrix.sh` family: `fv-lab-goldens.sh` writes its pod body from
/// `runpod-http.sh plan` like every tier's, and fv-lab's own dry run is its
/// golden (`fixtures/gold-dry-run.txt`).
pub const GOLD_TIER: &str = "gold";

/// The prompt of every gold cell: `runpod-matrix.sh`'s default `PROMPT`
/// (the `rtx6000` cells').
pub const GOLD_PROMPT: &str = "A man in his thirties talking to the camera in a bright living room, medium close-up, natural expressions and hand gestures, soft window light. He says: <d>Hello, this was generated entirely in Rust.</d>";

/// The seed when the gold file names none (`runpod-matrix.sh`'s `SEED`).
pub const DEFAULT_SEED: u64 = 1024;

/// `gold-<variant>`.
pub fn cell_name(variant: &str) -> String {
    format!("gold-{variant}")
}

/// The canonical cell of one gold file and its family variant.
pub fn gold_cell(g: &Gold, v: &VariantManifest) -> CellFile {
    let w = &g.workload;
    let variant = g.model.variant.as_str();
    let mut argv: Vec<String> = [
        "--keep-going",
        "--mode",
        "fast",
        "engine",
        "--model",
        variant,
        "--weights-root",
        "{weights}",
        "--prompt",
        "{prompt}",
        "--seed",
        "{seed}",
        "--width",
        "{width}",
        "--height",
        "{height}",
    ]
    .into_iter()
    .map(str::to_owned)
    .collect();
    if w.frames.is_some() {
        argv.extend(["--num-frames".to_owned(), "{frames}".to_owned()]);
    }
    argv.extend(["--clip-out".to_owned(), "{runs}/{arm}/out".to_owned()]);
    let length = match (w.frames, w.seconds) {
        (Some(f), _) => format!("{f} frames"),
        (None, Some(s)) => format!("the model's default length (the gold file's stream is {s} s)"),
        (None, None) => "the model's default length".to_owned(),
    };
    let seed_from = if w.seeds.is_empty() {
        "runpod-matrix.sh's SEED (the gold file names none)".to_owned()
    } else {
        "the gold file's first seed".to_owned()
    };
    let mut note = format!(
        "Generated by `fv-lab gold cells --write` from lab/gold/{variant}.toml and families/{}.toml: the served variant through the serve engine (fv-gpucheck engine: its recipe and technique profile from the family file), at the gold canvas {}x{} and {length}; one request of runpod-matrix.sh's default prompt (the gold prompt set `{}` is not run), seed: {seed_from}.",
        g.model.family, w.width, w.height, w.prompt_set
    );
    if !w.env.is_empty() {
        let keys: Vec<&str> = w.env.keys().map(String::as_str).collect();
        note.push_str(&format!(
            " The gold file's workload.env ({}) reproduces an older measurement and is not applied: the gold run measures the served default.",
            keys.join(", ")
        ));
    }
    CellFile {
        schema: CELL_SCHEMA,
        name: cell_name(variant),
        description: format!(
            "The gold cell of `{variant}`: the served variant through the serve engine at its gold canvas (fv-lab run gold)"
        ),
        workload: Workload {
            model: "engine".to_owned(),
            prompt: Some(GOLD_PROMPT.to_owned()),
            prompt_set: None,
            seed: Some(w.seeds.first().copied().unwrap_or(DEFAULT_SEED)),
            seconds: None,
            frames: w.frames,
            width: Some(w.width),
            height: Some(w.height),
            steps: None,
            note: Some(note),
        },
        lists: Default::default(),
        arms: vec![Arm {
            name: variant.to_owned(),
            gate: format!("variant:{variant}"),
            trees: v.trees.clone(),
            steps: w.steps,
            note: None,
            bin: ArmBin::Gpucheck,
            tae: None,
            env: None,
            argv,
        }],
        compares: Vec::new(),
        gates: Vec::new(),
    }
}

/// The file text of a gold cell: a header, then the cell as TOML.
pub fn cell_text(cell: &CellFile) -> Result<String, String> {
    let body = toml::to_string(cell).map_err(|e| format!("{}: {e}", cell.name))?;
    Ok(format!(
        "# GENERATED by `fv-lab gold cells --write` from lab/gold/ and families/ (docs/adr/0023-lab-report-and-ci-bridge.md §3).\n# Do not edit: change the gold file or the family file and regenerate; tests/gold_tier.rs fails on drift.\n{body}"
    ))
}

/// Every gold file's cell, in gold-file order, as `(cell name, file text)`.
pub fn gold_cells(golds: &[Gold], families: &FamilySet) -> Result<Vec<(String, String)>, String> {
    let mut out = Vec::with_capacity(golds.len());
    for g in golds {
        let v = &g.model.variant;
        let (_, var) = families
            .find(v)
            .filter(|(_, var)| var.id == *v)
            .ok_or_else(|| format!("lab/gold/{v}.toml: no family variant `{v}`"))?;
        let cell = gold_cell(g, var);
        cell.validate(&format!("lab/cells/{}.toml", cell.name))
            .map_err(|e| e.to_string())?;
        out.push((cell.name.clone(), cell_text(&cell)?));
    }
    Ok(out)
}

/// What differs between the committed gold cells and their generation: a
/// cell missing or changed, a `gold-*.toml` no gold file generates (an
/// orphan), and the `gold` tier's `cells` list against the generated names in
/// order. `committed` maps every `lab/cells/gold-*.toml` stem to its text;
/// `tier_cells` is the `gold` tier's list (`None`: no such tier). Empty when
/// current.
pub fn drift(
    committed: &std::collections::BTreeMap<String, String>,
    tier_cells: Option<&[String]>,
    generated: &[(String, String)],
) -> Vec<String> {
    let mut out = Vec::new();
    for (name, text) in generated {
        match committed.get(name) {
            None => out.push(format!("lab/cells/{name}.toml is missing")),
            Some(t) if t != text => {
                out.push(format!("lab/cells/{name}.toml differs from its gold file"))
            }
            Some(_) => {}
        }
    }
    for name in committed.keys() {
        if !generated.iter().any(|(n, _)| n == name) {
            out.push(format!(
                "lab/cells/{name}.toml is generated by no gold file (an orphan)"
            ));
        }
    }
    let names: Vec<String> = generated.iter().map(|(n, _)| n.clone()).collect();
    match tier_cells {
        None => out.push(format!("lab/tiers.toml has no `{GOLD_TIER}` tier")),
        Some(list) if list != names.as_slice() => out.push(format!(
            "the `{GOLD_TIER}` tier's cells in lab/tiers.toml are not the gold cells in gold-file order: cells = [{}]",
            names
                .iter()
                .map(|n| format!("\"{n}\""))
                .collect::<Vec<_>>()
                .join(", ")
        )),
        Some(_) => {}
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeMap;

    #[test]
    fn drift_names_missing_changed_orphan_and_list() {
        let gen = vec![
            ("gold-a".to_owned(), "A".to_owned()),
            ("gold-b".to_owned(), "B".to_owned()),
        ];
        let names = vec!["gold-a".to_owned(), "gold-b".to_owned()];
        let mut committed: BTreeMap<String, String> = gen.iter().cloned().collect();
        assert!(drift(&committed, Some(&names), &gen).is_empty());

        committed.insert("gold-old".into(), "X".into());
        committed.insert("gold-b".into(), "B2".into());
        committed.remove("gold-a");
        let d = drift(&committed, Some(&names[..1]), &gen);
        assert_eq!(d.len(), 4, "{d:?}");
        assert!(d[0].contains("gold-a.toml is missing"));
        assert!(d[1].contains("gold-b.toml differs"));
        assert!(d[2].contains("gold-old.toml is generated by no gold file"));
        assert!(d[3].contains("cells = [\"gold-a\", \"gold-b\"]"));
        assert_eq!(drift(&committed, None, &gen).len(), 4);
    }
}
