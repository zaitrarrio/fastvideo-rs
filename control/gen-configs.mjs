/** deploy/deploy.toml, validated against the family manifests and resolved for the generators: every model's
 * variant, family and recipe; whether a preset's config rides inline (its image does not carry it). */
export function parseDeploy(textIn, set = loadFamilies(), label = "deploy/deploy.toml") {
  const doc = parseToml(textIn);
  onlyKeys(doc, KEYS.top, label);
  if (doc.schema !== 1) throw new Error(`${label}: schema = ${JSON.stringify(doc.schema)}, want 1`);
  const dispatch = doc.dispatch ?? {};
  const famIds = set.families.map((f) => f.id);
  if (JSON.stringify(Object.keys(dispatch).sort()) !== JSON.stringify([...famIds].sort())) throw new Error(`${label}: dispatch names ${Object.keys(dispatch).join(", ")}, the families are ${famIds.join(", ")}`);
  for (const [k, v] of Object.entries(dispatch)) text(v, `${label}: dispatch.${k}`);
  const dispatchFams = new Set(Object.values(dispatch));

  const images = (doc.images ?? []).map((im, i) => {
    const at = `${label}: images[${i}]`;
    onlyKeys(im, KEYS.image, at);
    if (!ID_RE.test(im.id ?? "")) throw new Error(`${at}.id ${JSON.stringify(im.id)}`);
    if (!CONFIG_RE.test(im.config ?? "")) throw new Error(`${at}.config: a configs/serve file name`);
    const also = im.also ?? [];
    if (!strs(also) || also.some((c) => !CONFIG_RE.test(c) || c === im.config)) throw new Error(`${at}.also`);
    const compute = im.compute ?? "gpu";
    if (!["gpu", "cpu"].includes(compute)) throw new Error(`${at}.compute: gpu | cpu`);
    if (im.note !== undefined) text(im.note, `${at}.note`);
    return { id: im.id, config: im.config, also: [...also], compute, legacy: im.legacy === true, note: im.note ?? null };
  });
  const imageById = new Map();
  for (const im of images) {
    if (imageById.has(im.id)) throw new Error(`${label}: image ${im.id} twice`);
    imageById.set(im.id, im);
  }
  const servingImage = (id, at) => {
    const im = imageById.get(id);
    if (!im || im.legacy || im.compute !== "gpu") throw new Error(`${at}: ${JSON.stringify(id)} is not a GPU image variant (${images.filter((x) => !x.legacy && x.compute === "gpu").map((x) => x.id).join(", ")})`);
    return im;
  };
  const carries = (im, cfg) => im.config === cfg || im.also.includes(cfg);
  const covered = (trees, rel) => trees.some((t) => rel === t || rel.startsWith(t + "/"));

  const ids = new Set();
  const claim = (id, at) => {
    if (!ID_RE.test(id ?? "")) throw new Error(`${at}.id ${JSON.stringify(id)}: 1-31 lower-case letters, digits and '-'`);
    if (ids.has(id)) throw new Error(`${at}.id: preset ${id} twice`);
    ids.add(id);
  };
  const presets = (doc.presets ?? []).map((p, i) => {
    const at = `${label}: presets[${i}]`;
    onlyKeys(p, KEYS.preset, at);
    claim(p.id, at);
    text(p.title, `${at}.title`);
    text(p.description, `${at}.description`);
    const im = servingImage(p.image, `${at}.image`);
    if (!CONFIG_RE.test(p.config ?? "")) throw new Error(`${at}.config: a configs/serve file name`);
    if (!Array.isArray(p.models) || !p.models.length) throw new Error(`${at}.models: at least one`);
    const modelIds = new Set();
    const models = p.models.map((m, j) => {
      const mat = `${at}.models[${j}]`;
      onlyKeys(m, KEYS.model, mat);
      const v = set.variants.get(m.variant);
      if (!v) throw new Error(`${mat}.variant: ${JSON.stringify(m.variant)} is not a variant id of families/*.toml`);
      const recipe = m.recipe ?? v.id;
      if (recipeVariantOf(set, recipe)?.id !== v.id) throw new Error(`${mat}.recipe: ${JSON.stringify(recipe)} does not resolve to ${v.id} (a tier alias, the id or a served name of it)`);
      const id = m.id ?? v.id;
      if (modelIds.has(id)) throw new Error(`${mat}.id: ${id} twice`);
      modelIds.add(id);
      return { id, variant: v.id, family: v.family, recipe };
    });
    const trees = [...new Set(models.flatMap((m) => set.variants.get(m.variant).weight_trees))];
    const prequant = p.prequant ?? [];
    if (!strs(prequant)) throw new Error(`${at}.prequant`);
    for (const q of prequant) if (!covered(trees, q) || trees.includes(q)) throw new Error(`${at}.prequant: ${q} is not nested in one of the preset's weight trees (${trees.join(", ")})`);
    if (p.licence !== undefined) text(p.licence, `${at}.licence`);
    if (p.container_disk_gb !== undefined) posInt(p.container_disk_gb, `${at}.container_disk_gb`);
    if (p.standard !== undefined && typeof p.standard !== "boolean") throw new Error(`${at}.standard`);
    return {
      id: p.id,
      title: p.title,
      description: p.description,
      standard: p.standard === true,
      image: im.id,
      config: p.config,
      inline: !carries(im, p.config),
      ...(prequant.length ? { prequant: [...prequant] } : {}),
      ...(p.licence !== undefined ? { licence: p.licence } : {}),
      ...(p.container_disk_gb !== undefined ? { container_disk_gb: p.container_disk_gb } : {}),
      models,
      max_queued: posInt(p.max_queued, `${at}.max_queued`),
      job_timeout_s: posInt(p.job_timeout_s, `${at}.job_timeout_s`),
      stale_after_s: posInt(p.stale_after_s, `${at}.stale_after_s`),
    };
  });
  const presetById = new Map(presets.map((p) => [p.id, p]));
  const family_presets = (doc.family_presets ?? []).map((p, i) => {
    const at = `${label}: family_presets[${i}]`;
    onlyKeys(p, KEYS.family, at);
    claim(p.id, at);
    text(p.title, `${at}.title`);
    text(p.description, `${at}.description`);
    const im = servingImage(p.image, `${at}.image`);
    if (!CONFIG_RE.test(p.config ?? "")) throw new Error(`${at}.config: a configs/serve file name`);
    if (!strs(p.members) || !p.members.length || new Set(p.members).size !== p.members.length) throw new Error(`${at}.members: model preset ids, unique`);
    const members = p.members.map((id) => presetById.get(id) ?? (() => { throw new Error(`${at}.members: ${id} is not a model preset`); })());
    const variants = members.flatMap((m) => m.models.map((x) => set.variants.get(x.variant)));
    const fams = [...new Set(variants.map((v) => v.family))];
    if (fams.length !== 1) throw new Error(`${at}.members: one model family per process, not ${fams.join(", ")}`);
    const floor = Math.max(...variants.map((v) => v.gpu.min_vram_gib));
    if (posInt(p.min_vram_gb, `${at}.min_vram_gb`) < floor) throw new Error(`${at}.min_vram_gb ${p.min_vram_gb} is below its variants' gpu.min_vram_gib ${floor}`);
    const trees = [...new Set(variants.flatMap((v) => v.weight_trees))];
    const prequant = p.prequant ?? [];
    if (!strs(prequant)) throw new Error(`${at}.prequant`);
    for (const q of prequant) if (!covered(trees, q) || trees.includes(q)) throw new Error(`${at}.prequant: ${q} is not nested in one of the members' weight trees`);
    const left_out = (p.left_out ?? []).map((l, j) => {
      onlyKeys(l, ["what", "why"], `${at}.left_out[${j}]`);
      return { what: text(l.what, `${at}.left_out[${j}].what`), why: text(l.why, `${at}.left_out[${j}].why`) };
    });
    return { id: p.id, title: p.title, description: p.description, image: im.id, config: p.config, inline: !carries(im, p.config), min_vram_gb: p.min_vram_gb, members: [...p.members], prequant: [...prequant], left_out };
  });

  const gcpNames = new Set();
  const gcp = (doc.gcp ?? []).map((r, i) => {
    const at = `${label}: gcp[${i}]`;
    onlyKeys(r, KEYS.gcp, at);
    if (!ID_RE.test(r.name ?? "") || gcpNames.has(r.name)) throw new Error(`${at}.name ${JSON.stringify(r.name)}: unique, a lower-case id`);
    gcpNames.add(r.name);
    if (!CONFIG_RE.test(r.config ?? "")) throw new Error(`${at}.config`);
    if (r.runpod_twin !== undefined && !CONFIG_RE.test(r.runpod_twin)) throw new Error(`${at}.runpod_twin`);
    if (r.dispatch_family !== undefined && !dispatchFams.has(r.dispatch_family)) throw new Error(`${at}.dispatch_family ${r.dispatch_family}: one of ${[...dispatchFams].join(", ")}`);
    const cells = r.verify_cells ?? [];
    const served = r.served ?? [];
    if (!strs(cells) || cells.some((c) => /\s/.test(c))) throw new Error(`${at}.verify_cells`);
    if (!strs(served) || (r.runpod_twin !== undefined) === served.length > 0) throw new Error(`${at}.served: only (and then required) without a runpod_twin, which supplies them`);
    for (const k of ["machine", "fal_app", "minimax_model", "reactor_mode"]) text(r[k], `${at}.${k}`);
    return { name: r.name, config: r.config, runpod_twin: r.runpod_twin ?? null, dispatch_family: r.dispatch_family ?? null, verify_cells: [...cells], machine: r.machine, fal_app: r.fal_app, minimax_model: r.minimax_model, served: [...served], reactor_mode: r.reactor_mode };
  });

  onlyKeys(doc.autoscale ?? {}, ["pools"], `${label}: autoscale`);
  const poolNames = new Set();
  const pools = (doc.autoscale?.pools ?? []).map((p, i) => {
    const at = `${label}: autoscale.pools[${i}]`;
    if (typeof p.name !== "string" || !p.name || poolNames.has(p.name)) throw new Error(`${at}.name: unique, non-empty`);
    poolNames.add(p.name);
    if (!dispatchFams.has(p.family)) throw new Error(`${at}.family ${JSON.stringify(p.family)}: a dispatch family (${[...dispatchFams].join(", ")})`);
    volumePlacements(p, at);
    return p;
  });
  return { dispatch, images, presets, family_presets, gcp, autoscale_pools: pools };
}
/** Every table under `x` that names a `volume_id` must be the EU weights volume in its data centre (CLAUDE.md). */
function volumePlacements(x, at) {
  if (Array.isArray(x)) return x.forEach((y, i) => volumePlacements(y, `${at}[${i}]`));
  if (!x || typeof x !== "object") return;
  if ("volume_id" in x && (x.volume_id !== EU_VOLUME.volume_id || x.data_center !== EU_VOLUME.data_center))
    throw new Error(`${at}: volume ${JSON.stringify(x.volume_id)} in ${JSON.stringify(x.data_center)}: the only weights volume is ${EU_VOLUME.volume_id} in ${EU_VOLUME.data_center} (CLAUDE.md, EU only)`);
  for (const [k, v] of Object.entries(x)) volumePlacements(v, `${at}.${k}`);
}
