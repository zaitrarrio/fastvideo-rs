// Generates the controller's copies of the serve configs from
// configs/serve (the source of truth):
//   src/cluster/worker-configs.ts   the worker configs the pool presets send
//                                   inline (FV_WORKER_TOML_B64), so they run on
//                                   images whose variant does not carry them
//   src/cluster/image-configs.ts    which configs each per-variant image carries
//                                   (docker/gpucheck.Dockerfile serve-<variant>
//                                   stages), its baked FV_CONFIG, and their TOML
//                                   (what a serverless endpoint serves before a
//                                   worker boots, docs/control/serverless.md)
//   src/r2-trees.ts, src/r2-fetch-script.ts  the R2 weights store's published trees
//                                   (scripts/gpu/weights-r2.tsv) and the pod fetcher r2-fetch.py
//   src/serverless/console-assets.ts fv-serve's console pages and assets
//                                   (crates/fastvideo-serve/console, the
//                                   files console.rs embeds), served unchanged
//                                   by the serverless console proxy
//   node gen-configs.mjs            rewrite them
//   node gen-configs.mjs --check    exit 1 when they are stale (test/unit/payloads.test.ts runs the same check)
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SERVE = join(HERE, "../configs/serve");
const CONSOLE = join(HERE, "../crates/fastvideo-serve/console");

/** The worker configs src/cluster/spec.ts's presets send inline. */
export const INLINE_WORKER_CONFIGS = ["runpod-ltx-pro.toml", "runpod-ltx-a2v.toml", "runpod-ltx-ref2v.toml", "runpod-h3-ref2v.toml", "runpod-longlive.toml"];

const lit = (s) => "`" + s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`";

export function workerConfigsTs() {
  const entries = INLINE_WORKER_CONFIGS.map((n) => `  ${JSON.stringify(n)}: ${lit(readFileSync(join(SERVE, n), "utf8"))},`);
  return `// Generated by control/gen-configs.mjs from configs/serve: do not edit; edit
// the TOML and run \`node gen-configs.mjs\`. The pool presets
// (src/cluster/spec.ts) send these inline (FV_WORKER_TOML_B64).
export const WORKER_CONFIGS: Record<string, string> = {
${entries.join("\n")}
};
`;
}

/** The per-variant serve images' configs, read from the Dockerfile's serve-<variant> stages. */
export function imageConfigs() {
  const df = readFileSync(join(HERE, "../docker/gpucheck.Dockerfile"), "utf8");
  const out = {};
  let cur = null;
  for (const line of df.split("\n")) {
    const from = /^FROM\s+\S+\s+AS\s+serve-([a-z0-9-]+)\s*$/i.exec(line);
    if (from) {
      cur = ["build", "cuda-bin"].includes(from[1]) ? null : (out[from[1]] = { default: "", files: [] });
      continue;
    }
    if (/^FROM\s/i.test(line)) cur = null;
    if (!cur) continue;
    const cp = /^COPY\s+(.+)\s+\/etc\/fv\/\s*$/.exec(line);
    if (cp) for (const f of cp[1].split(/\s+/)) if (f.startsWith("configs/serve/")) cur.files.push(f.slice("configs/serve/".length));
    const env = /\bFV_CONFIG=(\S+)/.exec(line);
    if (/^ENV\s/.test(line) && env) cur.default = env[1];
  }
  return out;
}

export function imageConfigsTs() {
  const imgs = imageConfigs();
  const files = [...new Set(Object.values(imgs).flatMap((i) => i.files))].sort();
  const entries = files.map((n) => `  ${JSON.stringify(n)}: ${lit(readFileSync(join(SERVE, n), "utf8"))},`);
  return `// Generated by control/gen-configs.mjs from docker/gpucheck.Dockerfile and
// configs/serve: do not edit; run \`node gen-configs.mjs\`. Which worker configs
// each per-variant serve image carries under /etc/fv, its baked FV_CONFIG, and
// their TOML (what an endpoint serves, derived before a worker boots).
export const IMAGE_CONFIGS: Record<string, { default: string; files: string[] }> = ${JSON.stringify(imgs, null, 2)};

export const BAKED_CONFIGS: Record<string, string> = {
${entries.join("\n")}
};
`;
}

/** The console's files as console.rs serves them: pages by name (index.html → `/console`), assets with their content type. */
export function consoleAssetsTs() {
  const files = readdirSync(CONSOLE).filter((f) => /\.(html|js|css)$/.test(f)).sort();
  const type = (f) => (f.endsWith(".css") ? "text/css; charset=utf-8" : "text/javascript; charset=utf-8");
  const pages = files.filter((f) => f.endsWith(".html")).map((f) => `  ${JSON.stringify(f.replace(/\.html$/, ""))}: ${lit(readFileSync(join(CONSOLE, f), "utf8"))},`);
  const assets = files.filter((f) => !f.endsWith(".html")).map((f) => `  ${JSON.stringify(f)}: { type: ${JSON.stringify(type(f))}, body: ${lit(readFileSync(join(CONSOLE, f), "utf8"))} },`);
  // Vendored third-party assets (console/vendor/README.md), served flat as console.rs does.
  for (const [f, t] of [["hls.light.min.js", type("x.js")], ["hls.js-LICENSE.txt", "text/plain; charset=utf-8"]]) {
    assets.push(`  ${JSON.stringify(f)}: { type: ${JSON.stringify(t)}, body: ${lit(readFileSync(join(CONSOLE, "vendor", f), "utf8"))} },`);
  }
  return `// Generated by control/gen-configs.mjs from crates/fastvideo-serve/console: do
// not edit; edit the console and run \`node gen-configs.mjs\`. The serverless
// console proxy (src/serverless/console.ts) serves these unchanged.
export const CONSOLE_PAGES: Record<string, string> = {
${pages.join("\n")}
};
export const CONSOLE_ASSETS: Record<string, { type: string; body: string }> = {
${assets.join("\n")}
};
`;
}

const GPU = join(HERE, "../scripts/gpu");
const tsvRows = (file) =>
  readFileSync(join(GPU, file), "utf8")
    .split("\n")
    .filter((l) => l.trim() && !l.startsWith("#"))
    .map((l) => l.split("\t"));
/** The Hub source of every weight tree a GMI / Brev pod can fetch at boot (providers.ts, docs/serve/deploy-gmi-brev.md §7):
 * weights-manifest.tsv (dest, repo, globs) at the pinned revision of weights-revisions.tsv; only one-repo trees the plain
 * Hub fetcher can make (fetcher "hub", a 40-hex revision). The auxiliary/ url rows (pinned URL + SHA-256 + size) as well. */
export function weightsSourcesTs() {
  const revs = new Map();
  for (const [dest, repo, rev, , fetcher] of tsvRows("weights-revisions.tsv")) {
    const k = dest;
    if (!revs.has(k)) revs.set(k, []);
    revs.get(k).push({ repo, rev, fetcher });
  }
  const trees = [];
  const aux = [];
  for (const [dest, src, globs = "", meta = ""] of tsvRows("weights-manifest.tsv")) {
    if (src.startsWith("url:")) {
      const sha = /sha256:([0-9a-f]{64})/.exec(globs + " " + meta)?.[1];
      const size = /size:(\d+)/.exec(globs + " " + meta)?.[1];
      if (sha && size) aux.push(`  { path: ${JSON.stringify(dest)}, url: ${JSON.stringify(src.slice(4))}, sha256: ${JSON.stringify(sha)}, size: ${size} },`);
      continue;
    }
    const r = revs.get(dest) || [];
    if (r.length !== 1 || r[0].fetcher !== "hub" || r[0].repo !== src || !/^[0-9a-f]{40}$/.test(r[0].rev)) continue;
    trees.push(`  ${JSON.stringify(dest)}: { repo: ${JSON.stringify(src)}, revision: ${JSON.stringify(r[0].rev)}, globs: ${JSON.stringify(globs.split(" ").filter(Boolean))} },`);
  }
  return `// Generated by control/gen-configs.mjs from scripts/gpu/weights-manifest.tsv and
// weights-revisions.tsv: do not edit; edit the TSVs and run \`node gen-configs.mjs\`.
// The weight trees a GMI / Brev pod can fetch from the Hub at boot (weights_source
// hub, docs/serve/deploy-gmi-brev.md §7): one repo each, at a pinned revision.
export interface HubTree {
  repo: string;
  revision: string;
  globs: string[];
}
export const HUB_TREES: Record<string, HubTree> = {
${trees.join("\n")}
};
/** auxiliary/ files: a pinned URL, its SHA-256 and size (verify-weights.sh aux). */
export const AUX_FILES: { path: string; url: string; sha256: string; size: number }[] = [
${aux.join("\n")}
];
`;
}

/** The trees published in the R2 weights store (scripts/gpu/weights-r2.tsv, docs/ops/r2-weights.md): weights_source r2. */
export function r2TreesTs() {
  const rows = [];
  for (const [dest, rev, files, bytes, sha, source = ""] of tsvRows("weights-r2.tsv")) {
    if (!/^[0-9a-f]{64}$/.test(sha || "") || !/^\d+$/.test(bytes || "") || !/^\d+$/.test(files || "")) throw new Error(`weights-r2.tsv: bad row for ${dest}`);
    rows.push(`  ${JSON.stringify(dest)}: { rev: ${JSON.stringify(rev)}, files: ${files}, bytes: ${bytes}, manifest_sha256: ${JSON.stringify(sha)}, source: ${JSON.stringify(source)} },`);
  }
  return `// Generated by control/gen-configs.mjs from scripts/gpu/weights-r2.tsv: do not edit; publish with
// scripts/gpu/r2-weights.py, add the row (\`r2-weights.py record\`) and run \`node gen-configs.mjs\`.
// The trees in the R2 weights store (weights_source r2, docs/ops/r2-weights.md): the revision, size and the
// SHA-256 of the manifest fv-control accepts (manifests/<dest>/<rev>.json).
export interface R2Tree {
  rev: string;
  files: number;
  bytes: number;
  manifest_sha256: string;
  source: string;
}
export const R2_TREES: Record<string, R2Tree> = ${rows.length ? `{\n${rows.join("\n")}\n}` : "{}"};
`;
}

/** The pod-side fetcher (scripts/gpu/r2-fetch.py) fv-control serves at /ingest/v1/r2-fetch.py, with its SHA-256 (the boot checks it). */
export function r2FetchScriptTs() {
  const py = readFileSync(join(GPU, "r2-fetch.py"), "utf8");
  return `// Generated by control/gen-configs.mjs from scripts/gpu/r2-fetch.py: do not edit; edit the script and run
// \`node gen-configs.mjs\`. Served at GET /ingest/v1/r2-fetch.py; pods check it against R2_FETCH_SHA256.
export const R2_FETCH_SHA256 = ${JSON.stringify(createHash("sha256").update(py, "utf8").digest("hex"))};
export const R2_FETCH_PY = ${lit(py)};
`;
}

export const OUTPUTS = {
  "src/cluster/worker-configs.ts": workerConfigsTs,
  "src/cluster/image-configs.ts": imageConfigsTs,
  "src/serverless/console-assets.ts": consoleAssetsTs,
  "src/weights-sources.ts": weightsSourcesTs,
  "src/r2-trees.ts": r2TreesTs,
  "src/r2-fetch-script.ts": r2FetchScriptTs,
};

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [rel, gen] of Object.entries(OUTPUTS)) {
    const p = join(HERE, rel);
    const want = gen();
    let cur = "";
    try {
      cur = readFileSync(p, "utf8");
    } catch {}
    if (cur === want) continue;
    stale++;
    if (check) console.error(`stale: ${rel} (run: node gen-configs.mjs)`);
    else writeFileSync(p, want), console.log(`wrote ${rel}`);
  }
  if (check && stale) process.exit(1);
}
